import { readFileSync, writeFileSync } from 'node:fs';
const root = new URL('../lib/i18n/', import.meta.url);
const tr = JSON.parse(readFileSync(new URL('tr.json', root), 'utf8'));
const en = JSON.parse(readFileSync(new URL('en.json', root), 'utf8'));
const placeholders = text => [...text.matchAll(/\{(\w+)\}/g)].map(match => match[1]).sort();
if (JSON.stringify(Object.keys(tr).sort()) !== JSON.stringify(Object.keys(en).sort())) throw Error('i18n: dictionary keys differ');
const lines = ['// Generated by node scripts/generate-i18n.mjs. Do not edit by hand.', 'export type MessageValue = string | number | boolean | null | undefined;', 'export type Parameters = {'];
for (const [key, text] of Object.entries(tr)) {
  if (!text.trim() || !en[key]?.trim()) throw Error(`i18n: empty message ${key}`);
  const names = placeholders(text);
  if (JSON.stringify(names) !== JSON.stringify(placeholders(en[key]))) throw Error(`i18n: placeholder mismatch ${key}`);
  if (names.length) lines.push(`  ${JSON.stringify(key)}: { ${[...new Set(names)].map(name => `${name}: MessageValue`).join('; ')} };`);
}
lines.push('};', '');
const output = lines.join('\n'), target = new URL('parameters.ts', root);
if (process.argv.includes('--check')) {
  if (readFileSync(target, 'utf8') !== output) throw Error('i18n: parameter types are stale; run node scripts/generate-i18n.mjs');
} else writeFileSync(target, output);
// Retain the installed application's id, origin and URLs; localize only presentation.
const manifestUrl = new URL('../public/manifest.json', import.meta.url);
const baseManifest = JSON.parse(readFileSync(manifestUrl, 'utf8'));
for (const [locale, catalog] of [['tr', tr], ['en', en]]) {
  const url = locale === 'en' ? manifestUrl : new URL('../public/manifest.tr.json', import.meta.url);
  const manifest = JSON.stringify({...baseManifest, lang: locale, description: catalog['meta.description']}, null, 2) + '\n';
  if (process.argv.includes('--check')) {
    if (readFileSync(url, 'utf8') !== manifest) throw Error(`i18n: stale ${locale} manifest`);
  } else writeFileSync(url, manifest);
}
console.log(`i18n: ${Object.keys(tr).length} messages, matching keys and placeholders`);
